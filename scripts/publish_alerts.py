#!/usr/bin/env python3
"""Publish a single GitHub issue for actionable NEW public listing signals.

The repository owner's GitHub notification settings determine email delivery.
This never claims that a February lease start or an all-in monthly rent was
verified. All content is public, based only on public apartment listings.
"""
import json
import os
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PATH = ROOT / "data" / "alerts.json"


def main():
    if not PATH.exists():
        print("No alerts file; skip.")
        return
    data = json.loads(PATH.read_text(encoding="utf-8"))
    events = data.get("events") or []
    if not events:
        print("No new alert events; skip.")
        return
    date = str(data.get("generated", ""))[:10]
    title = f"Apartment watch: {len(events)} new price / unit leads ({date})"
    body = [
        "Automatically discovered public listing changes. **These are not "
        "confirmed February 7, 2027 availability or all-in quotes.**",
        "",
    ]
    for event in events[:20]:
        price = event.get("price")
        label = "Price decrease" if event.get("kind") == "unit-price-drop" else "Newly observed 1BR"
        difference = (f" (from \${event['previousPrice']:,})"
                      if "previousPrice" in event else "")
        body.append(
            f"- **{label}: {event['building']} unit {event['unit']}** — "
            f"\${price:,} {event.get('priceBasis', 'unknown')} rent{difference}. "
            f"[Listing source]({event.get('sourceUrl', '')})."
        )
    body.extend([
        "",
        "Verify actual unit availability, parking, mandatory fees, washer/dryer, "
        "lease duration, and whether the property will accept February 7.",
        "",
        "_Generated by the apartment research GitHub Actions workflow._",
    ])
    if not os.environ.get("GH_TOKEN"):
        print("GH_TOKEN absent; site alerts still generated, no GitHub issue.")
        return
    subprocess.run(["gh", "issue", "create", "--title", title, "--body", "\n".join(body)],
                   cwd=ROOT, check=True)
    print(f"Published public GitHub notification issue with {len(events)} leads.")


if __name__ == "__main__":
    main()
